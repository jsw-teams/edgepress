// Vendor the upstream Unicode subsets; site builds and visitors need no font CDN.
import {createHash} from 'node:crypto';
import {mkdtemp, mkdir, readFile, writeFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve, basename} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';

const run = promisify(execFile);
const root = fileURLToPath(new URL('../../', import.meta.url));
const destination = resolve(root, 'static/edgepress/fonts');
const version = '5.3.0';
const families = ['noto-sans', 'noto-serif', 'noto-sans-sc', 'noto-sans-tc'];
const temporary = await mkdtemp(resolve(tmpdir(), 'edgepress-fonts-'));
const digest = (bytes, algorithm = 'sha256', encoding = 'hex') => createHash(algorithm).update(bytes).digest(encoding);
const assets = new Map();
const provenance = [];
let stylesheet = '/* Noto, SIL OFL 1.1. Generated by tools/assets/sync-fonts.mjs. */\n';
async function get(url) {
  const response = await fetch(url, {signal: AbortSignal.timeout(60000)});
  if (!response.ok) throw new Error('Font download failed: ' + response.status + ' ' + url);
  return response;
}
try {
  for (const id of families) {
    const name = '@fontsource-variable/' + id;
    const metadata = await (await get('https://registry.npmjs.org/' + encodeURIComponent(name) + '/' + version)).json();
    const archive = Buffer.from(await (await get(metadata.dist.tarball)).arrayBuffer());
    if (metadata.dist.integrity !== 'sha512-' + digest(archive, 'sha512', 'base64')) throw new Error('Font archive integrity mismatch: ' + name);
    const archivePath = resolve(temporary, id + '.tgz');
    const extracted = resolve(temporary, id);
    await writeFile(archivePath, archive);
    await mkdir(extracted);
    await run('tar', ['-xf', archivePath, '-C', extracted]);
    const source = resolve(extracted, 'package');
    let css = await readFile(resolve(source, 'index.css'), 'utf8');
    const files = [];
    for (const original of new Set([...css.matchAll(/url\(\.\/files\/([^\s)]+)\)/g)].map(match => match[1]))) {
      if (basename(original) !== original || !original.endsWith('.woff2')) throw new Error('Unexpected font filename: ' + original);
      const bytes = await readFile(resolve(source, 'files', original));
      const sha256 = digest(bytes);
      const file = original.replace(/\.woff2$/, '.' + sha256.slice(0, 16) + '.woff2');
      assets.set(file, bytes);
      files.push({file, sha256, bytes: bytes.length});
      css = css.replaceAll('./files/' + original, '/edgepress/fonts/' + file);
    }
    stylesheet += css + '\n';
    const license = id + '-OFL.txt';
    assets.set(license, await readFile(resolve(source, 'LICENSE')));
    provenance.push({package: name, version, integrity: metadata.dist.integrity,
      upstream: 'https://github.com/google/fonts/tree/main/ofl/' + id.replaceAll('-', ''),
      metadata: JSON.parse(await readFile(resolve(source, 'metadata.json'), 'utf8')), license, files});
  }
  await mkdir(destination, {recursive: true});
  // Only rotate generated fonts listed by the previous manifest.
  const old = await readFile(resolve(destination, 'provenance.json'), 'utf8').then(JSON.parse).catch(error => {
    if (error.code === 'ENOENT') return []; throw error;
  });
  for (const item of old) for (const {file} of item.files) {
    if (basename(file) !== file) throw new Error('Invalid previous font manifest');
    if (!assets.has(file)) await rm(resolve(destination, file));
  }
  for (const [file, bytes] of assets) await writeFile(resolve(destination, file), bytes);
  await writeFile(resolve(destination, 'faces.css'), stylesheet);
  await writeFile(resolve(destination, 'provenance.json'), JSON.stringify(provenance, null, 2) + '\n');
  console.log('Vendored ' + [...assets.keys()].filter(file => file.endsWith('.woff2')).length + ' Unicode font subsets (' +
    ([...assets.values()].reduce((sum, bytes) => sum + bytes.length, 0) / 1048576).toFixed(2) + ' MiB).');
} finally {
  await rm(temporary, {recursive: true, force: true});
}
